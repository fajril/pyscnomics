logger = logging.getLogger("pyscnomics.api.errors")

REQUEST_ID_HEADER = "X-Request-ID"
_REQUEST_ID_HEADER_LOWER = REQUEST_ID_HEADER.lower()

# Upstream error headers that must never be copied onto a regenerated JSON 5xx.
# Body-framing/hop-by-hop headers do not describe the new body, entity
# representation metadata (encoding, range, checksums, validators) is stale for
# the regenerated bytes, CORS response headers are owned by CORSMiddleware, and
# credential-bearing headers must never be reflected.
_UNSAFE_ERROR_HEADERS = frozenset(
    {
        # Body framing / hop-by-hop.
        "connection",
        "content-length",
        "content-type",
        "keep-alive",
        "te",
        "trailer",
        "transfer-encoding",
        "upgrade",
        # Stale entity representation metadata for the regenerated body.
        "content-encoding",
        "content-range",
        "content-md5",
        "digest",
        "content-language",
        "content-location",
        "content-disposition",
        "etag",
        "last-modified",
        # Credential-bearing headers that must never be reflected.
        "authorization",
        "proxy-authorization",
        "x-api-key",
    }
)
_CORS_RESPONSE_HEADERS = frozenset(
    {
        "access-control-allow-credentials",
        "access-control-allow-headers",
        "access-control-allow-methods",
        "access-control-allow-origin",
        "access-control-expose-headers",
        "access-control-max-age",
    }
)

_RequestHandler = Callable[[Request], Awaitable[Response]]

# Sol-approved structural copy. These strings are asserted by tests and the
# frontend, so they must not embed raw Python paths or error codes.
STRUCTURAL_MESSAGE = "This input could not be read in the required format."
STRUCTURAL_GUIDANCE = (
    "Open the indicated input, correct its format, then select Check again."
)
_LEGACY_DETAIL_LIMIT = 500
_ENTERED_VALUE_LIMIT = 200

_FINITE_ERROR_TYPES = frozenset({"finite_number"})
_NUMERIC_PARSING_ERROR_TYPES = frozenset(
    {"int_parsing", "float_parsing", "decimal_parsing"}
)
# A fractional value supplied to an integer-only field: genuine but fixable by
# entering a whole number.
_WHOLE_NUMBER_ERROR_TYPES = frozenset({"int_from_float"})
# Array/tuple branch tags used by pydantic union diagnostics.
_ARRAY_BRANCH = re.compile(r"^(?:list|set|frozenset|tuple|Sequence)\[")

# Pydantic inserts a union-branch tag into ``loc`` (for example
# ``list[float]``, ``list[int]``, ``float`` or ``none``). Those labels are not
# part of the submitted payload and must not appear in normalized locations.
_BARE_TYPE_LABELS = frozenset(
    {
        "any",
        "bool",
        "bytes",
        "date",
        "datetime",
        "decimal",
        "float",
        "int",
        "none",
        "str",
        "time",
        "timedelta",
        "uuid",
    }
)
_GENERIC_TYPE_LABEL = re.compile(r"^[A-Za-z_][A-Za-z0-9_.]*\[.*\]$")

# Bounded internal-diagnostics limits. The server keeps a useful but fixed-size
# debug record. Nothing here reads the request body or authorization headers,
# and captured local variables are never included.
_MAX_EXCEPTION_TEXT = 1000
_MAX_CAUSE_TEXT = 1000
_MAX_STACK_TEXT = 8000
_MAX_DIAGNOSTIC_TEXT = 12000


def _truncate(text: str, limit: int) -> str:
    """Cap ``text`` to ``limit`` characters with a trailing ellipsis."""
    if len(text) <= limit:
        return text
    return text[: limit - 1] + "…"


def _safe_exception_text(exc: BaseException) -> str:
    """Return a bounded ``str(exc)`` that survives a hostile ``__str__``."""
    try:
        text = str(exc)
    except Exception:
        try:
            text = repr(exc)
        except Exception:
            return f"<unprintable {type(exc).__name__}>"
    return _truncate(text, _MAX_EXCEPTION_TEXT)


def _bounded_cause(exc: BaseException) -> str:
    """Describe the exception's cause/context chain, bounded and object-free."""
    cause = exc.__cause__ if exc.__cause__ is not None else exc.__context__
    if cause is None:
        return ""
    label = "caused by" if exc.__cause__ is not None else "context"
    return _truncate(
        f"{label} {type(cause).__name__}: {_safe_exception_text(cause)}",
        _MAX_CAUSE_TEXT,
    )


def _bounded_traceback(exc: BaseException) -> str:
    """Render a fixed-size traceback with no captured local variables."""
    try:
        rendered = "".join(
            traceback.TracebackException.from_exception(
                exc, capture_locals=False
            ).format()
        )
    except Exception:
        return f"<traceback unavailable for {type(exc).__name__}>"
    return _truncate(rendered, _MAX_STACK_TEXT)


def format_bounded_diagnostics(
    exc: BaseException, *, request_id: str, path: str
) -> str:
    """Build one bounded, leak-safe internal-failure diagnostic string.

    The record identifies the request, path, and exception type, then carries a
    capped message, cause, and stack. It never includes the request body,
    authorization headers, or captured local variables, and it cannot raise even
    when the exception's ``str``/``repr`` are hostile.
    """
    lines = [
        (
            "Unhandled request failure "
            f"(request_id={request_id}, path={path}, "
            f"exception={type(exc).__name__})"
        ),
        f"message: {_safe_exception_text(exc)}",
    ]
    cause = _bounded_cause(exc)
    if cause:
        lines.append(f"cause: {cause}")
    lines.append("stack:")
    lines.append(_bounded_traceback(exc))
    return _truncate("\n".join(lines), _MAX_DIAGNOSTIC_TEXT)


def get_request_id(request: Request) -> str:
    """Return the server-generated reference for this request.

    The value lives on ``request.state`` so the middleware, exception handlers,
    and route handlers all observe the same reference. Inbound ``X-Request-ID``
    headers are deliberately ignored and never echoed back.
    """
    existing = getattr(request.state, "request_id", None)
    if isinstance(existing, str) and existing:
        return existing
    request_id = uuid.uuid4().hex
    request.state.request_id = request_id
    return request_id


def _safe_error_headers(headers: Mapping[str, str] | None) -> dict[str, str]:
    """Filter upstream error headers before they reach a regenerated 5xx.

    Any case variant of ``X-Request-ID`` is discarded (the server reference is
    added separately), CORS response headers are dropped so the actual
    CORSMiddleware owns the allowed-origin policy, and body/hop-by-hop headers
    that do not describe the regenerated JSON are removed. Useful standard
    headers such as ``Retry-After`` are retained.
    """
    if not headers:
        return {}
    safe: dict[str, str] = {}
    for name, value in headers.items():
        lowered = name.lower()
        if lowered in _UNSAFE_ERROR_HEADERS or lowered in _CORS_RESPONSE_HEADERS:
            continue
        if lowered == _REQUEST_ID_HEADER_LOWER:
            continue
        safe[name] = value
    return safe


def _json_response(
    body: dict[str, object],
    *,
    status_code: int,
    request_id: str,
    headers: Mapping[str, str] | None = None,
) -> JSONResponse:
    # Discard any case variant of the reference header so the server-generated
    # value is the only one; a case-sensitive dict override would let an
    # upstream ``x-request-id`` survive and be comma-joined by the ASGI server.
    merged: dict[str, str] = {
        name: value
        for name, value in (headers or {}).items()
        if name.lower() != _REQUEST_ID_HEADER_LOWER
    }
    merged[REQUEST_ID_HEADER] = request_id
    return JSONResponse(content=body, status_code=status_code, headers=merged)


def _legacy_detail(errors: tuple[ValidationIssue, ...]) -> str:
    """Build the bounded ``PyscErr:`` detail from the first verified issue."""
    if not errors:
        return "PyscErr: Input validation failed."
    first = errors[0]
    text = first.message
    if first.guidance:
        text = f"{text} {first.guidance}"
    text = " ".join(text.split())
    if len(text) > _LEGACY_DETAIL_LIMIT:
        text = text[: _LEGACY_DETAIL_LIMIT - 1].rstrip() + "…"
    return f"PyscErr: {text}"


def validation_error_response(
    exc: InputValidationError, request_id: str
) -> JSONResponse:
    """Render a structured 422 response for a known input problem.

    The shared envelope is authoritative; a concise ``PyscErr:`` detail string
    carrying the first verified message and its guidance is retained during the
    compatibility window. The envelope ``message`` keeps the group count.
    """
    errors = exc.errors
    envelope = ValidationEnvelope(
        schema_version=1,
        kind="input_validation",
        message=validation_message(errors),
        request_id=request_id,
        validation_complete=exc.validation_complete,
        errors=errors,
        warnings=exc.warnings,
        skipped_checks=exc.skipped_checks,
    )
    body: dict[str, object] = dict(envelope.to_json())
    body["detail"] = _legacy_detail(errors)
    return _json_response(body, status_code=422, request_id=request_id)


def _success_message(report: ValidationReport) -> str:
    if report.errors:
        return validation_message(report.errors)
    if not report.validation_complete or report.skipped_checks:
        return (
            "Input checks could not be completed. Some checks were skipped "
            "because required input is missing or invalid."
        )
    message = validation_message(())
    if report.warnings:
        message = f"{message} {len(report.warnings)} warnings need review."
    return message


def validation_success_response(
    report: ValidationReport, request_id: str
) -> JSONResponse:
    """Render a validation-only HTTP 200 response with ``can_calculate``."""
    envelope = ValidationEnvelope(
        schema_version=1,
        kind="input_validation",
        message=_success_message(report),
        request_id=request_id,
        validation_complete=report.validation_complete,
        errors=report.errors,
        warnings=report.warnings,
        skipped_checks=report.skipped_checks,
        can_calculate=report.can_calculate,
    )
    return _json_response(
        dict(envelope.to_json()), status_code=200, request_id=request_id
    )


def _reason_phrase(status_code: int) -> str:
    """Return the generic HTTP reason phrase for a status code.

    A generic phrase keeps internal server details out of the client body.
    """
    try:
        return HTTPStatus(status_code).phrase
    except ValueError:
        return "Server Error"


def _server_error_message(status_code: int, request_id: str) -> str:
    """Return the Sol-approved copy for an internal or unavailable service."""
    if status_code == 503:
        return (
            "The calculation service is currently unavailable. Try again later. "
            f"If the problem continues, copy reference {request_id} when reporting it."
        )
    return (
        "The calculation service could not complete this request. Try again. "
        f"If the problem continues, copy reference {request_id} when reporting it."
    )


def server_error_response(
    request_id: str,
    *,
    status_code: int = 500,
    headers: Mapping[str, str] | None = None,
) -> JSONResponse:
    """Render the unexpected-failure envelope without leaking a traceback.

    Any 5xx status is preserved exactly and ``headers`` (for example
    ``Retry-After``) are retained, while the server-generated reference always
    replaces any inbound or upstream ``X-Request-ID``.
    """
    envelope = ValidationEnvelope(
        schema_version=1,
        kind="server_error",
        message=_server_error_message(status_code, request_id),
        request_id=request_id,
        validation_complete=False,
    )
    body: dict[str, object] = dict(envelope.to_json())
    body["detail"] = _reason_phrase(status_code)
    return _json_response(
        body,
        status_code=status_code,
        request_id=request_id,
        headers=_safe_error_headers(headers),
    )


def _is_type_label(segment: str) -> bool:
    return (
        segment in _BARE_TYPE_LABELS
        or bool(_GENERIC_TYPE_LABEL.match(segment))
        or segment.endswith("BM")
    )


_UNKNOWN = object()


def _strip_leading_body(loc: Sequence[object]) -> list[object]:
    """Drop only the initial FastAPI ``body`` prefix segment."""
    segments = list(loc)
    if segments and segments[0] == "body":
        return segments[1:]
    return segments


def _descend(container: object, key: str | int) -> object:
    if isinstance(container, Mapping):
        mapping = cast(Mapping[object, object], container)
        if isinstance(key, str) and key in mapping:
            return mapping[key]
        return _UNKNOWN
    if isinstance(container, (list, tuple)):
        sequence = cast("list[object] | tuple[object, ...]", container)
        if (
            isinstance(key, int)
            and not isinstance(key, bool)
            and 0 <= key < len(sequence)
        ):
            return sequence[key]
        return _UNKNOWN
    return _UNKNOWN


def _walk_loc(
    loc: Sequence[object], body: object
) -> tuple[tuple[str | int, ...], tuple[str, ...]]:
    """Walk a pydantic ``loc`` against the actual body.

    Returns the normalized path plus the union-branch tags that were skipped
    (for example ``list[float]``). Only the leading ``body`` prefix is stripped
    unconditionally. A string segment is kept whenever it is a real key in the
    current container; it is recorded as a union-branch tag only when it does
    not exist in the container and looks like a pydantic type label. A string
    that neither exists nor looks like a type tag is treated as a genuinely
    missing field and kept. This never deletes an actual submitted mapping key,
    so user table names such as ``float``, ``int``, ``body``, ``SomeBM`` or
    ``list[float]`` survive.
    """
    result: list[str | int] = []
    branches: list[str] = []
    cursor: object = body
    for segment in _strip_leading_body(loc):
        if isinstance(segment, bool):
            result.append(str(segment))
            cursor = _UNKNOWN
            continue
        if isinstance(segment, int):
            result.append(segment)
            cursor = _descend(cursor, segment)
            continue
        if isinstance(segment, str):
            container = cursor
            if isinstance(container, Mapping):
                mapping = cast(Mapping[object, object], container)
                if segment in mapping:
                    result.append(segment)
                    cursor = mapping[segment]
                    continue
                if _is_type_label(segment):
                    branches.append(segment)
                    continue
                result.append(segment)
                cursor = _UNKNOWN
                continue
            if _is_type_label(segment):
                branches.append(segment)
                continue
            result.append(segment)
            cursor = _UNKNOWN
            continue
        result.append(str(segment))
        cursor = _UNKNOWN
    return tuple(result), tuple(branches)


def _is_array_branch(branch: str) -> bool:
    return bool(_ARRAY_BRANCH.match(branch))


def _branch_numeric_kind(branch: str) -> str | None:
    """Classify a union-branch tag as a ``float`` or ``int`` numeric branch."""
    if branch in ("float", "complex"):
        return "float"
    if branch in ("int", "bool"):
        return "int"
    match = _ARRAY_BRANCH.match(branch)
    inner = branch[match.end() : -1] if match else branch
    if "float" in inner:
        return "float"
    if "int" in inner:
        return "int"
    return None


def _union_field_path(
    path: tuple[str | int, ...], branch: str | None
) -> tuple[str | int, ...]:
    """Return the union field location (row index removed for array branches)."""
    if (
        branch is not None
        and _is_array_branch(branch)
        and path
        and isinstance(path[-1], int)
        and not isinstance(path[-1], bool)
    ):
        return path[:-1]
    return path


