def _field_label(name: str) -> str:
    mapped = _VISIBLE_LABELS.get(name)
    if mapped is not None:
        return mapped
    words = name.replace("_", " ").strip()
    if not words:
        return name
    return words[0].upper() + words[1:]


def _visible_field(path: tuple[str | int, ...]) -> str | None:
    for segment in reversed(path):
        if isinstance(segment, str):
            return _field_label(segment)
    return None


def _json_safe(value: object) -> object:
    """Return a strict-JSON-safe copy of a diagnostic value.

    Non-finite floats become their string form so the response can never fail
    strict JSON serialization. Mapping keys are coerced to strings.
    """
    if isinstance(value, float):
        if not math.isfinite(value):
            return repr(value)
        return value
    if value is None or isinstance(value, (str, bool, int)):
        return value
    if isinstance(value, Mapping):
        mapping = cast(Mapping[object, object], value)
        return {str(key): _json_safe(item) for key, item in mapping.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        sequence = cast("Sequence[object]", value)
        return [_json_safe(item) for item in sequence]
    return str(value)


def _safe_scalar(value: object) -> object:
    """Return a bounded, object-free representation for issue context."""
    if value is None or isinstance(value, (bool, int)):
        return value
    if isinstance(value, str):
        return value[:_ENTERED_VALUE_LIMIT]
    if isinstance(value, float):
        return value if math.isfinite(value) else repr(value)
    return type(value).__name__


def _error_message(error_type: str, field_label: str | None) -> str:
    target = field_label or "This input"
    if error_type in _FINITE_ERROR_TYPES:
        return f"{target} must be a finite number."
    if error_type in _WHOLE_NUMBER_ERROR_TYPES:
        return f"{target} must be a whole number."
    if error_type in _NUMERIC_PARSING_ERROR_TYPES:
        return f"{target} needs a number."
    return STRUCTURAL_MESSAGE


def _error_code(error_type: str) -> str:
    if error_type in _FINITE_ERROR_TYPES:
        return "NUMERIC_FIELD_NOT_FINITE"
    if error_type in _WHOLE_NUMBER_ERROR_TYPES:
        return "NUMERIC_FIELD_NOT_INTEGER"
    if error_type in _NUMERIC_PARSING_ERROR_TYPES:
        return "NUMERIC_FIELD_NOT_A_NUMBER"
    return "INPUT_FORMAT_INVALID"


def _loc_sequence(error: Mapping[str, object]) -> Sequence[object]:
    raw = error.get("loc")
    if isinstance(raw, (list, tuple)):
        return cast("Sequence[object]", raw)
    return ()


@dataclass(frozen=True)
class _Diagnostic:
    """One pydantic diagnostic resolved against the submitted body."""

    error: Mapping[str, object]
    path: tuple[str | int, ...]
    branch: str | None
    field_path: tuple[str | int, ...]
    error_type: str
    field: str | None

    @property
    def code(self) -> str:
        return _error_code(self.error_type)

    @property
    def message(self) -> str:
        return _error_message(self.error_type, self.field)


def _build_diagnostics(
    raw_errors: Sequence[Mapping[str, object]], body: object
) -> list[_Diagnostic]:
    diagnostics: list[_Diagnostic] = []
    for error in raw_errors:
        error_type = str(error.get("type", ""))
        path, branches = _walk_loc(_loc_sequence(error), body)
        branch = branches[0] if branches else None
        diagnostics.append(
            _Diagnostic(
                error=error,
                path=path,
                branch=branch,
                field_path=_union_field_path(path, branch),
                error_type=error_type,
                field=_visible_field(path),
            )
        )
    return diagnostics


def _authoritative_fields(
    diagnostics: Sequence[_Diagnostic],
) -> tuple[dict[tuple[str | int, ...], str], set[tuple[str | int, ...]]]:
    """Decide per union field which branch is authoritative.

    When a field offers both a numeric ``float`` and ``int`` branch, the float
    branch is a superset (it accepts decimals), so it is authoritative and the
    rejected int-branch diagnostics are not reported as issues. Other
    multi-branch unions with no numeric authority are collapsed to a single
    conservative field-level format issue.
    """
    branches_by_field: dict[tuple[str | int, ...], set[str]] = {}
    for diagnostic in diagnostics:
        if diagnostic.branch is not None:
            branches_by_field.setdefault(diagnostic.field_path, set()).add(
                diagnostic.branch
            )
    authoritative: dict[tuple[str | int, ...], str] = {}
    collapse: set[tuple[str | int, ...]] = set()
    for field_path, branches in branches_by_field.items():
        kinds = {_branch_numeric_kind(branch) for branch in branches}
        kinds.discard(None)
        if "float" in kinds and "int" in kinds:
            authoritative[field_path] = "float"
        elif len(branches) >= 2:
            collapse.add(field_path)
    return authoritative, collapse


def _issue_context(diagnostic: _Diagnostic) -> dict[str, JsonValue]:
    return {
        "field": diagnostic.field,
        "technical_detail": cast(
            JsonValue,
            {
                "type": diagnostic.error_type,
                "input": _safe_scalar(diagnostic.error.get("input")),
            },
        ),
    }


def _diagnostic_to_issue(
    diagnostic: _Diagnostic,
    *,
    path: tuple[str | int, ...] | None = None,
    code: str | None = None,
    message: str | None = None,
) -> ValidationIssue:
    effective_path = diagnostic.path if path is None else path
    return ValidationIssue(
        code=diagnostic.code if code is None else code,
        severity="error",
        message=diagnostic.message if message is None else message,
        guidance=STRUCTURAL_GUIDANCE,
        locations=(IssueLocation(effective_path),) if effective_path else (),
        context=_issue_context(diagnostic),
    )


def _issues_from_diagnostics(
    diagnostics: Sequence[_Diagnostic],
) -> tuple[ValidationIssue, ...]:
    """Turn pydantic diagnostics into genuine, deduplicated input issues."""
    authoritative, collapse = _authoritative_fields(diagnostics)
    issues: list[ValidationIssue] = []
    collapsed: set[tuple[str | int, ...]] = set()
    for diagnostic in diagnostics:
        if diagnostic.branch is None:
            issues.append(_diagnostic_to_issue(diagnostic))
            continue
        if diagnostic.field_path in authoritative:
            if _branch_numeric_kind(diagnostic.branch) == "float":
                issues.append(_diagnostic_to_issue(diagnostic))
            continue
        if diagnostic.field_path in collapse:
            if diagnostic.field_path in collapsed:
                continue
            collapsed.add(diagnostic.field_path)
            issues.append(
                _diagnostic_to_issue(
                    diagnostic,
                    path=diagnostic.field_path,
                    code="INPUT_FORMAT_INVALID",
                    message=STRUCTURAL_MESSAGE,
                )
            )
            continue
        issues.append(_diagnostic_to_issue(diagnostic))
    return tuple(issues)


def _sanitize_detail_entry(error: Mapping[str, object]) -> dict[str, object]:
    entry: dict[str, object] = {}
    for key in ("type", "loc", "msg", "input", "ctx", "url"):
        if key in error:
            entry[key] = _json_safe(error[key])
    return entry


def validation_request_error_response(
    exc: RequestValidationError, request_id: str
) -> JSONResponse:
    """Render a 422 for a malformed request.

    Every pydantic diagnostic is preserved as an issue and as a standard
    ``detail`` entry. Normalized issue locations address the real payload while
    the standard detail retains pydantic's diagnostic union branches.
    """
    raw_errors = cast("list[Mapping[str, object]]", list(exc.errors()))
    submitted_body: object = cast(object, exc.body)
    diagnostics = _build_diagnostics(raw_errors, submitted_body)
    issues = _issues_from_diagnostics(diagnostics)
    detail = [_sanitize_detail_entry(error) for error in raw_errors]
    blocking_paths = tuple(
        location for issue in issues for location in issue.locations
    )[:10]
    skipped = (
        SkippedCheck(
            scope="dependent_input_checks",
            reason=(
                "Structural format problems prevented dependent input checks "
                "from running. Fix the indicated input, then select Check again."
            ),
            blocking_paths=blocking_paths,
        ),
    )
    envelope = ValidationEnvelope(
        schema_version=1,
        kind="input_validation",
        message=STRUCTURAL_MESSAGE,
        request_id=request_id,
        validation_complete=False,
        errors=issues,
        skipped_checks=skipped,
    )
    response_body: dict[str, object] = dict(envelope.to_json())
    response_body["detail"] = detail
    return _json_response(response_body, status_code=422, request_id=request_id)


def install_error_handlers(app: FastAPI) -> None:
    """Install the input-validation, HTTP, and unexpected-failure handlers.

    Typed handlers cover structured domain errors, malformed requests, and
    explicit ``HTTPException`` responses. Unexpected failures are caught by an
    HTTP middleware rather than a generic ``Exception`` handler, so the
    resulting 500 response still passes back through the CORS middleware and
    exposes the request-ID header to allowed origins. Explicit 5xx responses are
    normalized to the same safe server-error envelope while non-5xx responses
    keep FastAPI's standard shape.
    """

    @app.exception_handler(InputValidationError)
    async def _handle_input_validation(  # pyright: ignore[reportUnusedFunction]
        request: Request, exc: InputValidationError
    ) -> JSONResponse:
        request_id = get_request_id(request)
        return validation_error_response(exc, request_id)

    @app.exception_handler(RequestValidationError)
    async def _handle_request_validation(  # pyright: ignore[reportUnusedFunction]
        request: Request, exc: RequestValidationError
    ) -> JSONResponse:
        request_id = get_request_id(request)
        return validation_request_error_response(exc, request_id)

    @app.exception_handler(StarletteHTTPException)
    async def _handle_http_exception(  # pyright: ignore[reportUnusedFunction]
        request: Request, exc: StarletteHTTPException
    ) -> Response:
        # Only genuine 5xx responses are normalized. Everything else (204/304
        # no-content, 401 ``WWW-Authenticate``, 4xx detail/status/headers) is
        # delegated to FastAPI's own handler so its exact semantics are kept.
        if not 500 <= exc.status_code < 600:
            return await http_exception_handler(request, exc)
        request_id = get_request_id(request)
        logger.error(
            "%s",
            format_bounded_diagnostics(
                exc, request_id=request_id, path=request.url.path
            ),
        )
        return server_error_response(
            request_id,
            status_code=exc.status_code,
            headers=exc.headers,
        )

    @app.middleware("http")
    async def _catch_unexpected(  # pyright: ignore[reportUnusedFunction]
        request: Request, call_next: _RequestHandler
    ) -> Response:
        try:
            return await call_next(request)
        except Exception as exc:  # noqa: BLE001 - deliberate catch-all boundary
            request_id = get_request_id(request)
            logger.error(
                "%s",
                format_bounded_diagnostics(
                    exc, request_id=request_id, path=request.url.path
                ),
            )
            return server_error_response(request_id)
