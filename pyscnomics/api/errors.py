"""FastAPI error handlers for the shared input-validation contract.

Two distinct 422 shapes are produced:

* Structured domain input errors (``InputValidationError``) render the shared
  envelope with a concise ``PyscErr:`` legacy ``detail`` string.
* Structural request errors (``RequestValidationError``) render the same
  envelope plus a sanitized standard ``detail`` array so pydantic diagnostics
  (``type``, ``loc``, ``msg``, ``input``) remain available.

Both share a server-generated request reference that is stored on
``request.state`` so every response path for a request reports the same id.
"""

